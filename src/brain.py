import os
import json
from google import genai
from google.genai import types
from dotenv import load_dotenv
from pathlib import Path

# Load API key from the .env file you created earlier
load_dotenv()
API_KEY = os.getenv("GEMINI_API_KEY")

if not API_KEY:
    raise ValueError("GEMINI_API_KEY not found in .env file. Please add it!")

client = genai.Client()

class SynestheticBrain:
    def __init__(self, model_name="gemini-1.5-flash"):
        print(f"[Brain] Booting NLU Engine ({model_name})...")
        
        self.model_name = model_name

        # The System Prompt: This is the core logic engine of the entire project
        system_instruction = """
        You are the 'Synesthetic Director', an AI architect that translates acoustic and linguistic data into cinematic visual prompts for an AI image generator (Stable Diffusion).
        
        You will receive a JSON payload containing a global tempo (BPM) and a timeline of audio segments. Each segment contains text and 4 mathematical acoustic features:
        1. rms_energy (Volume) -> Dictates lighting intensity and environmental turbulence.
        2. spectral_centroid (Brightness) -> Dictates the color palette (low = dark/warm/heavy, high = bright/neon/cool).
        3. zcr (Chaos/Percussion) -> Dictates film grain, glitch effects, or visual harshness.
        4. spectral_bandwidth (Scale/Thickness) -> Dictates camera framing (low = macro/close-up, high = sweeping wide/epic landscape).

        TASK: 
        Analyze the emotional tone of the text and the mathematical acoustic features for each segment. 
        Generate a highly detailed, comma-separated image generation prompt tailored for a cinematic, highly-aesthetic sci-fi/surrealist style (e.g., Blade Runner, Dune, or brutalism).
        
        OUTPUT FORMAT:
        You must output strictly as a JSON array of objects. Each object must contain:
        - "start" (float): The start time.
        - "end" (float): The end time.
        - "prompt" (string): The vivid Stable Diffusion prompt (e.g., "cinematic ultra-wide shot, brutalist monolith, neon rain, heavy shadows, 8k resolution, highly detailed").
        - "negative_prompt" (string): Things the image generator should avoid (e.g., "blurry, text, watermark, deformed, low contrast").
        - "color_palette" (string): A short description of the colors.
        - "camera_movement" (string): A simulated camera movement (e.g., "Slow zoom in", "Aggressive shake", "Static").
        """
        
        # Initialize the model with the system instructions and forced JSON output
        self.config=types.GenerateContentConfig(
            response_mime_type="application/json",
            system_instruction=system_instruction)

    def generate_visual_script(self, acoustic_json_path, output_dir="output"):
        """Feeds the acoustic data to Gemini to generate the visual script. """
        file_path = Path(acoustic_json_path)
        if not file_path.exists():
            raise FileNotFoundError(f"Could not find input data: {acoustic_json_path}")
            
        print(f"\n--- Translating Data: {file_path.name} ---")
        
        with open(file_path, 'r', encoding='utf-8') as f:
            audio_data = json.load(f)
            
        # Send the raw JSON payload to Gemini
        print("[Brain] Sending timeline to Gemini for synesthetic translation...")
        
        try:
            # response = self.model.generate_content(json.dumps(audio_data))
            response = client.models.generate_content(
                model = self.model_name,
                contents = json.dumps(audio_data),
                config=self.config
            )
            
            visual_script = json.loads(response.text)
        except Exception as e:
            print(f"[Brain] ERROR: Failed to generate or parse response. {e}")
            return None
            
        # Ensure the output directory exists
        out_dir = Path(output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        
        # Save the final visual script
        output_file = out_dir / f"{file_path.stem}_visual_script.json"
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(visual_script, f, indent=4, ensure_ascii=False)
            
        print(f"[Brain] Masterpiece drafted! Script saved to: {output_file}\n")
        return output_file

